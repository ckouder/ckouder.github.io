<h2>Artist Statement</h2>

<section lang="en">
	<h3>English</h3>

	<p>
		I have come to think of language as an observer. It attends to feeling, volition, and wish, and
		it seems, for me, to work in two directions.
	</p>

	<p>
		Turned inward, on my own body, it is descriptive. When I say “I'm in pain” or “I'm fine,” the
		words reach for a sensation only I can know, and dissolve against it — feeling runs along a
		continuous spectrum, while language lands on discrete points. Inward, language falters, and what
		it cannot hold sinks back into the unnamed: the wordless residue the body keeps as memory.
	</p>

	<p>
		Turned outward, on others and the world, it is prescriptive. To name is to impose a shape — to
		begin a thing while excluding all that the name cannot hold. Outward, language stops being a
		report and becomes an opinion, a definition, a power. We live inside the wishes of others,
		inside words placed on us before we could choose them.
	</p>

	<p>
		What unsettles me is that these are not two faculties but one. The thing that cannot hold my own
		sensation is the same thing that carries the memory of the human past and leans on its future.
		Language is older and larger than I am; we speak it, and are spoken by it. From where I stand,
		it observes the state of a body, the history of a people, the direction of a species — and in
		observing, it moves us, the way a story we are told can change what we believe against the
		evidence of our own eyes.
	</p>

	<p>
		I paint and build in order to stand inside this and watch it work. A face dissolving into flesh
		and structure; a single word — <em>Cell</em>, <em>God</em>, <em>Fuji Mountain</em> — set into an ordinary
		room for a stranger to make sense of. They are small instruments for feeling, rather than proving,
		how language holds us, fails us, and carries us toward a place none of us has named.
	</p>

	<p>
		I cannot tell you that any of this is true. To say that language <em>is</em> an observer, as though
		I were stating a fact, would be to aim a name outward and mistake it for the world — the very gesture
		I distrust. So I do not declare it; I describe it, from where I happen to stand, and leave its completion
		to you.
	</p>
</section>

<section lang="zh">
	<h3>中文</h3>

	<p>我渐渐把语言看作一个观察者。它观察感受、意志与愿望；而在我看来，它朝两个方向运作。</p>

	<p>
		朝内，朝向我自己的身体时，它是描述性的。当我说“我痛”或“我没事”，词语伸向一种只有我自己能知道的感觉，却在它面前消解——感受是一道连续的光谱，语言却只能落在离散的点上。向内，语言总会失效；它无法容纳的部分沉回“无名”之中，成为身体以记忆形式留存的、无词的残余。
	</p>

	<p>
		朝外，朝向他人与世界时，它是规定性的。命名，就是强加一个形状——让一物开始存在，同时排除掉一切不合此名之物。向外，语言不再是陈述，而成为观点、定义、权力。我们活在他人的意愿里，活在那些早在我们能够选择之前，就被安置在我们身上的词语里。
	</p>

	<p>
		让我不安的是：这并非两种机能，而是同一种。那个连我自身感受都无法容纳的东西，正是承载着人类过去的记忆、并倚向其未来的东西。语言比我更古老、更宏大；我们言说它，也被它言说。从我所站的位置看去，它观察着一具身体的此刻、一个民族的历史、一个物种的方向——而在观察的同时，它推动着我们，正如一个被讲述的故事会改变我们的相信，哪怕它与我们亲眼所见相悖。
	</p>

	<p>
		我作画、造物，是为了站进这架机器之中，看它如何运转。一张脸消解为血肉与结构；一个词——“细胞”“神”“富士山”——被放进一个寻常的房间，交给一个陌生人去揣摩。它们是一些微小的器具，用来去感受，而非证明：语言如何容纳我们、辜负我们，又将我们带向一个谁都未曾命名的所在。
	</p>

	<p>
		而这一切，我都无法作为真理告诉你。若说“语言就是一个观察者”，仿佛在陈述一个事实，那便是把一个名字朝外抛出、又将它误认作世界——正是我所警惕的那个动作。所以我不宣告它；我只是描述它，从我恰好站立的位置，并把其余的部分，交给你来完成。
	</p>
</section>
